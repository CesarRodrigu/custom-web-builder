/**
 * Category contract of the configuration package and of the editor that
 * writes it.
 *
 * `categorySchema` is the exported document the front-end loads from
 * `categories/**`: the generated id, the name, the optional description and
 * the product references. `categoryDraftSchema` extends it with the
 * editor-only numeric id and drops the references, because membership is never
 * stored in the draft: the `categories` arrays of the products remain its
 * single source of truth. `Category` is the config entry, the document without
 * its id and references.
 */
import { z } from "astro/zod";

import { ValidationCode, isFilled } from "./validation";

/**
 * Reference from a category to one entry of the products collection.
 *
 * This is the shape a resolved category document exposes, not the on-disk
 * format: the exported document stores the entry ids as strings.
 */
export const productReferenceSchema = z.object({
  /** Collection the reference points to; categories only reference `products`. */
  collection: z.string(),
  /** Entry id relative to the `products` collection, e.g. `panes/baguette`. */
  id: z.string(),
});

/** Reference from a category to one entry of the products collection. */
export type ProductReference = z.infer<typeof productReferenceSchema>;

/**
 * Properties of the exported category document, with their types and no
 * validation rules.
 *
 * The full document applies its id rule to this shape, and the stored draft
 * derives its partial from it, so one property list reaches every variant.
 */
export const categoryShape = z.object({
  /** Stable unique id generated by the exporter from the category name. */
  id: z.string(),
  /** Display name of the category. */
  name: z.string(),
  /** Free text shown under the name, when provided. */
  description: z.string().optional(),
  /** Entry ids of the products that belong to the category, in display order. */
  products: z.array(z.string()),
});

/** Zod schema of the exported category document. */
export const categorySchema = categoryShape.extend({
  /** Stable unique id generated by the exporter from the category name. */
  id: z.string().refine(isFilled, ValidationCode.Required),
});

/** Category document read by the front-end from `categories/**`. */
export type CategoryDocument = z.infer<typeof categorySchema>;

/** Normalized category of the configuration the generator exports. */
export type Category = Pick<
  z.input<typeof categorySchema>,
  "name" | "description"
>;

/**
 * Properties of a category as edited in the form, with no validation rules.
 *
 * It drops the references of the exported document, which the draft never
 * stores, and uses the editor-only numeric id. The stored draft derives its
 * partial from this shape.
 */
export const categoryDraftShape = categoryShape
  .omit({ id: true, products: true })
  .extend({
    /** Incremental id of the category row. */
    id: z.number(),
    /** Display name of the category. */
    name: z.string(),
    /** Free description of the category. */
    description: z.string(),
  });

/**
 * Zod schema of a category as edited in the form.
 *
 * It applies the editing rules to `categoryDraftShape`, so the fields the form
 * always renders stay required even when blank and the editor can report them.
 */
export const categoryDraftSchema = categoryDraftShape.extend({
  /** Incremental id of the category row. */
  id: z.number({ error: ValidationCode.Required }).int().positive(),
  /** Display name of the category; blank is reported as required. */
  name: z.string().refine(isFilled, ValidationCode.Required),
});

/**
 * Category as edited in the form: a named group with a free description. Its
 * products are not stored here; they are read from the `categories` arrays of
 * the products, which stay the single source of truth for membership.
 */
export type CategoryDraft = z.input<typeof categoryDraftSchema>;
